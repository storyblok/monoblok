/**
 * SPIKE — generates the `<migration>.before.ts` snapshot a migration's `Before`
 * type parameter is read from.
 *
 * In the real design this runs as part of `schema push`, from the schema that
 * was just pushed. Here it reads the live space instead, which is the same
 * shape and additionally proves the snapshot survives a MAPI round trip.
 *
 * The snapshot is scoped: the blocks the migration names, plus every block
 * reachable from them through a `component_whitelist`. It is committed next to
 * the migration and frozen once shipped.
 *
 *   node scripts/generate-before-snapshot.mjs --blocks spike_article --out migrations/0001-rename-article-author.before.ts
 */
import { mkdir, writeFile } from "node:fs/promises";
import { dirname } from "node:path";
import process from "node:process";

const args = process.argv.slice(2);
const flag = (name) => {
  const at = args.indexOf(`--${name}`);
  return at === -1 ? undefined : args[at + 1];
};

const roots = (flag("blocks") ?? "").split(",").filter(Boolean);
const out = flag("out");
const token = process.env.STORYBLOK_TOKEN;
const space = flag("space") ?? process.env.STORYBLOK_SPACE_ID;

if (roots.length === 0 || !out) {
  console.error("Usage: --blocks <a,b> --out <path.before.ts> [--space <id>]");
  process.exit(2);
}
if (!token || !space) {
  console.error("Missing STORYBLOK_TOKEN / STORYBLOK_SPACE_ID.");
  process.exit(2);
}

const response = await fetch(`https://mapi.storyblok.com/v1/spaces/${space}/components`, {
  headers: { Authorization: token },
});
if (!response.ok) {
  console.error(`GET components -> ${response.status}`);
  process.exit(1);
}
const { components } = await response.json();
const byName = new Map(components.map((component) => [component.name, component]));

/** Server-assigned or position-derived keys the DSL does not author. */
const DROPPED_FIELD_KEYS = new Set(["id", "pos"]);

function whitelistOf(component) {
  return Object.values(component.schema ?? {}).flatMap((field) =>
    Array.isArray(field.component_whitelist) ? field.component_whitelist : [],
  );
}

// Closure over `component_whitelist`, so the snapshot types nested `bloks`
// fields as their real child content rather than as an open union.
const scope = new Set();
const queue = [...roots];
while (queue.length > 0) {
  const name = queue.shift();
  if (scope.has(name) || !byName.has(name)) continue;
  scope.add(name);
  queue.push(...whitelistOf(byName.get(name)));
}

const missing = roots.filter((name) => !byName.has(name));
if (missing.length > 0) {
  console.error(`Unknown blocks in space ${space}: ${missing.join(", ")}`);
  process.exit(1);
}

const camel = (name) => name.replace(/[_-](\w)/g, (_, c) => c.toUpperCase());
const constName = (name) => `${camel(name)}Block`;

function renderField(name, field) {
  const options = Object.fromEntries(
    Object.entries(field).filter(([key]) => !DROPPED_FIELD_KEYS.has(key)),
  );
  // `component_whitelist` is the wire name; the DSL spells it `allow`.
  if (Array.isArray(options.component_whitelist)) {
    options.allow = options.component_whitelist;
    delete options.component_whitelist;
    delete options.restrict_components;
    delete options.restrict_type;
    if (Array.isArray(options.component_denylist) && options.component_denylist.length === 0) {
      delete options.component_denylist;
    }
  }
  const rendered = Object.entries(options)
    .map(([key, value]) => `${key}: ${JSON.stringify(value)}`)
    .join(", ");
  return `    defineField(${JSON.stringify(name)}, { ${rendered} }),`;
}

function renderBlock(component) {
  const fields = Object.entries(component.schema ?? {})
    .sort((a, b) => (a[1].pos ?? 0) - (b[1].pos ?? 0))
    .map(([name, field]) => renderField(name, field))
    .join("\n");
  return [
    `export const ${constName(component.name)} = defineBlock({`,
    `  name: ${JSON.stringify(component.name)},`,
    `  is_root: ${Boolean(component.is_root)},`,
    `  is_nestable: ${Boolean(component.is_nestable)},`,
    `  fields: [`,
    fields,
    `  ],`,
    `});`,
  ].join("\n");
}

const ordered = [...scope].sort();
const body = [
  `/**`,
  ` * GENERATED by \`schema push\` — do not edit.`,
  ` *`,
  ` * The schema as it stood before ${out.split("/").pop().replace(".before.ts", "")} ran,`,
  ` * scoped to the blocks that migration touches plus everything reachable from`,
  ` * them. Frozen once shipped: later schema changes must not move it, or the`,
  ` * migration would start reading paths that did not exist when it was written.`,
  ` */`,
  `import { defineBlock, defineField, defineSchema } from "@storyblok/schema";`,
  `import type { Schema } from "@storyblok/schema";`,
  ``,
  ...ordered.map((name) => `${renderBlock(byName.get(name))}\n`),
  `const schema = defineSchema({`,
  `  blocks: { ${ordered.map((name) => constName(name)).join(", ")} },`,
  `});`,
  ``,
  `export type Before = Schema<typeof schema>;`,
  ``,
].join("\n");

await mkdir(dirname(out), { recursive: true });
await writeFile(out, body);
console.log(
  JSON.stringify({
    outcome: "PASS",
    function: "generate-before-snapshot",
    total: ordered.length,
    details: `${out}: ${ordered.join(", ")}`,
  }),
);
