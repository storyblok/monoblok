import type { ResourceLine } from "../pipe";
import type { TableColumn } from "../ui";
import type { Payload, ResourceFields } from "./fields";

export type ResourceRecord = ResourceLine;

/** A record as `list` and `get` print it: each secret field replaced by a `has_<field>` flag. */
export type ListedRecord<T extends ResourceRecord> = T & Record<`has_${string}`, boolean>;

export type Noun = {
  singular: string;
  plural: string;
};

export type CrudVerb = "list" | "get" | "create" | "update" | "delete";

/**
 * Where a resource's records live. Every resource so far belongs to a space;
 * a nested resource (datasource entries) adds its parent here.
 */
export type CrudScope = {
  spaceId: number;
};

/**
 * What a resource supplies to get `list`, `get`, `create`, `update` and
 * `delete` commands. Everything else is shared.
 */
export interface CrudResource<T extends ResourceRecord = ResourceRecord> {
  noun: Noun;
  /** Generated by `generate:openapi`; see `scripts/generate.ts`. */
  fields: ResourceFields;
  /** Fields never printed, logged or diffed by value. Not marked in the API spec. */
  secretFields: readonly (keyof T & string)[];
  /**
   * The field the API keeps unique per space. Enables targets by name and
   * `--if-not-exists`. Leave out for a resource without one: targets are then
   * IDs only.
   */
  nameField?: keyof T & string;
  /** `list` table columns. Write results get their own fixed columns. */
  columns: TableColumn<ListedRecord<T>>[];
  connect: (scope: CrudScope) => CrudOperations<T>;
}

export interface CrudOperations<T extends ResourceRecord = ResourceRecord> {
  /**
   * Every record, paging if the API pages. One call per run backs targets,
   * staleness checks and the name pre-check.
   */
  listAll: () => Promise<T[]>;
  get: (id: number) => Promise<T>;
  create: (payload: Payload) => Promise<T>;
  update: (id: number, payload: Payload) => Promise<T>;
  delete: (id: number) => Promise<void>;
  /**
   * Values a field accepts, for dry-run validation and for the `details` of a
   * 422 on that field. Called at most once per run.
   */
  allowedValues?: Record<string, () => Promise<string[]>>;
}
